# TRUSTGUARD AI - DEPLOYMENT READINESS ASSESSOR
# ============================================================


# ============================================================
# Severity configuration
# ============================================================

SEVERITY_WEIGHTS = {
    "CRITICAL": 30,
    "HIGH": 20,
    "MEDIUM": 10,
    "LOW": 5,
    "INFO": 0
}


# ============================================================
# Readiness thresholds
# ============================================================

def determine_status(
    score: float,
    critical_count: int,
    high_count: int
) -> str:

    # Any critical vulnerability blocks deployment.
    if critical_count > 0:
        return "NOT READY"

    # Multiple high-risk findings also block deployment.
    if high_count >= 2:
        return "NOT READY"

    # A single high vulnerability requires remediation.
    if high_count == 1:
        return "CONDITIONAL"

    if score >= 85:
        return "READY"

    if score >= 70:
        return "CONDITIONAL"

    return "NOT READY"


# ============================================================
# Risk level
# ============================================================

def determine_risk_level(
    score: float
) -> str:

    if score >= 85:
        return "LOW"

    if score >= 70:
        return "MEDIUM"

    if score >= 50:
        return "HIGH"

    return "CRITICAL"


# ============================================================
# Main assessment function
# ============================================================

def assess_deployment_readiness(
    vulnerabilities: List[Dict[str, Any]]
) -> Dict[str, Any]:

    """
    Assess whether a smart contract is ready for deployment.

    Parameters
    ----------
    vulnerabilities:
        Prioritized vulnerability findings generated by
        TrustGuard AI.

    Returns
    -------
    Dictionary containing deployment readiness information.
    """

    if vulnerabilities is None:
        vulnerabilities = []

    # ========================================================
    # Count vulnerabilities by severity
    # ========================================================

    counts = {
        "CRITICAL": 0,
        "HIGH": 0,
        "MEDIUM": 0,
        "LOW": 0,
        "INFO": 0
    }

    for vulnerability in vulnerabilities:

        severity = str(
            vulnerability.get(
                "severity",
                "INFO"
            )
        ).upper()

        if severity not in counts:
            severity = "INFO"

        counts[severity] += 1

    # ========================================================
    # Calculate risk penalty
    # ========================================================

    risk_penalty = 0.0

    for severity, count in counts.items():

        risk_penalty += (
            SEVERITY_WEIGHTS[severity]
            * count
        )

    # ========================================================
    # Additional penalty for detected findings
    # ========================================================

    detected_count = 0

    for vulnerability in vulnerabilities:

        if vulnerability.get(
            "detected",
            True
        ):

            detected_count += 1

    # ========================================================
    # Calculate readiness score
    # ========================================================

    readiness_score = (
        100.0
        - risk_penalty
    )

    # Small penalty for the overall number of
    # detected findings.
    if detected_count > 4:

        readiness_score -= (
            (detected_count - 4)
            * 2
        )

    readiness_score = max(
        0.0,
        min(
            100.0,
            readiness_score
        )
    )

    # ========================================================
    # Determine status
    # ========================================================

    status = determine_status(
        score=readiness_score,
        critical_count=counts[
            "CRITICAL"
        ],
        high_count=counts[
            "HIGH"
        ]
    )

    # ========================================================
    # Determine risk
    # ========================================================

    risk_level = determine_risk_level(
        readiness_score
    )

    # ========================================================
    # Blocking issues
    # ========================================================

    blocking_issues = []

    for vulnerability in vulnerabilities:

        severity = str(
            vulnerability.get(
                "severity",
                "INFO"
            )
        ).upper()

        if severity in {
            "CRITICAL",
            "HIGH"
        }:

            blocking_issues.append(
                {
                    "vulnerability":
                        vulnerability.get(
                            "vulnerability",
                            "Unknown"
                        ),

                    "severity":
                        severity,

                    "priority":
                        vulnerability.get(
                            "priority"
                        ),

                    "priority_score":
                        vulnerability.get(
                            "priority_score"
                        )
                }
            )

    # ========================================================
    # Recommendations
    # ========================================================

    recommendations = []

    if counts["CRITICAL"] > 0:

        recommendations.append(
            "Critical vulnerabilities must be "
            "resolved before deployment."
        )

    if counts["HIGH"] > 0:

        recommendations.append(
            "High-severity vulnerabilities should "
            "be remediated before deployment."
        )

    if counts["MEDIUM"] > 0:

        recommendations.append(
            "Review and remediate medium-severity "
            "findings before production deployment."
        )

    if counts["LOW"] > 0:

        recommendations.append(
            "Review low-severity findings as part "
            "of the final security review."
        )

    if not vulnerabilities:

        recommendations.append(
            "No detected vulnerabilities were supplied "
            "to the readiness assessor."
        )

    if status == "READY":

        recommendations.append(
            "Contract can proceed toward deployment "
            "after completing the normal testing and "
            "security review process."
        )

    elif status == "CONDITIONAL":

        recommendations.append(
            "Deployment should proceed only after "
            "the identified high-risk issues are "
            "reviewed and appropriately remediated."
        )

    else:

        recommendations.append(
            "Contract should not be deployed until "
            "blocking security findings are addressed."
        )

    # ========================================================
    # Final result
    # ========================================================

    return {

        "status":
            status,

        "readiness_score":
            round(
                readiness_score,
                1
            ),

        "risk_level":
            risk_level,

        "vulnerability_counts":
            counts,

        "total_findings":
            len(
                vulnerabilities
            ),

        "detected_findings":
            detected_count,

        "blocking_issues":
            blocking_issues,

        "recommendations":
            recommendations
    }


# ============================================================
# Human-readable report
# ============================================================

def print_readiness_report(
    result: Dict[str, Any]
) -> None:

    print("\n" + "=" * 70)

    print(
        "TRUSTGUARD AI - DEPLOYMENT READINESS ASSESSMENT"
    )

    print("=" * 70)

    print(
        f"\nStatus         : "
        f"{result['status']}"
    )

    print(
        f"Readiness Score: "
        f"{result['readiness_score']:.1f}/100"
    )

    print(
        f"Risk Level     : "
        f"{result['risk_level']}"
    )

    print(
        f"Total Findings : "
        f"{result['total_findings']}"
    )

    print(
        f"Detected       : "
        f"{result['detected_findings']}"
    )

    print("\nVULNERABILITY COUNTS")
    print("-" * 70)

    counts = result[
        "vulnerability_counts"
    ]

    print(
        f"Critical : {counts['CRITICAL']}"
    )

    print(
        f"High     : {counts['HIGH']}"
    )

    print(
        f"Medium   : {counts['MEDIUM']}"
    )

    print(
        f"Low      : {counts['LOW']}"
    )

    print(
        f"Info     : {counts['INFO']}"
    )

    print("\nBLOCKING ISSUES")
    print("-" * 70)

    if not result[
        "blocking_issues"
    ]:

        print(
            "None"
        )

    else:

        for issue in result[
            "blocking_issues"
        ]:

            print(
                f"{issue['vulnerability']} "
                f"→ "
                f"{issue['severity']}"
            )

    print("\nRECOMMENDATIONS")
    print("-" * 70)

    for recommendation in result[
        "recommendations"
    ]:

        print(
            f"→ {recommendation}"
        )

    print("\n" + "=" * 70)

    print(
        "DEPLOYMENT READINESS ASSESSMENT COMPLETE"
    )

    print("=" * 70)


